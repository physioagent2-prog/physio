from fastapi import APIRouter, Depends, HTTPException
from backend.supabase_client import get_supabase
from backend.auth_middleware import get_current_user
from typing import List

from backend.services.ai_service import ai_service

router = APIRouter()

# ASSESSMENTS
@router.post("/assessments")
async def create_assessment(data: dict, current_user: dict = Depends(get_current_user)):
    supabase = get_supabase()
    resp = supabase.table("assessments").insert(data).execute()
    return resp.data[0]

@router.get("/assessments/{patient_id}")
async def get_assessment(patient_id: str, current_user: dict = Depends(get_current_user)):
    supabase = get_supabase()
    resp = supabase.table("assessments").select("*").eq("patient_id", patient_id).order("created_at", desc=True).limit(1).execute()
    return resp.data[0] if resp.data else None

# AI TREATMENT GENERATION
@router.post("/generate/{patient_id}")
async def generate_plan(patient_id: str, current_user: dict = Depends(get_current_user)):
    supabase = get_supabase()
    
    # 1. Fetch Patient Info
    patient = supabase.table("patients").select("*").eq("id", patient_id).single().execute()
    
    # 2. Fetch Latest Assessment
    assessment = supabase.table("assessments").select("*").eq("patient_id", patient_id).order("created_at", desc=True).limit(1).execute()
    
    if not assessment.data:
        raise HTTPException(status_code=400, detail="No assessment found for this patient. Please complete an assessment first.")
    
    # 3. Generate Plan via Claude
    plan_text = await ai_service.generate_treatment_plan(patient.data, assessment.data[0])
    
    # 4. Save to session_plans table
    save_data = {
        "patient_id": patient_id,
        "short_term_goals": "Generated by AI",
        "notes": plan_text,
        "status": "draft"
    }
    resp = supabase.table("session_plans").insert(save_data).execute()
    
    return resp.data[0]

# SESSION DESIGNS (Formerly Treatment Plans)
@router.post("/session-plans")
async def create_session_plan(data: dict, current_user: dict = Depends(get_current_user)):
    supabase = get_supabase()
    
    # Build a clean, validated payload
    insert_data = {
        "patient_id":       data.get("patient_id"),
        "session_number":   int(data.get("session_number", 1)),
        "short_term_goals": data.get("short_term_goals"),
        "long_term_goals":  data.get("long_term_goals"),
        "frequency":        data.get("frequency"),
        "duration_weeks":   data.get("duration_weeks"),
        "modalities":       data.get("modalities"),
        "therapist_notes":  data.get("therapist_notes"),
        "status":           data.get("status", "active"),
        "clinical_snapshot": data.get("clinical_snapshot")
    }
    
    insert_data = {k: v for k, v in insert_data.items() if v is not None}
    
    # Use upsert to handle updates to the same session number gracefully
    resp = supabase.table("session_plans").upsert(insert_data, on_conflict="patient_id,session_number").execute()
    if not resp.data:
        raise HTTPException(status_code=400, detail="Failed to save session plan")
    return resp.data[0]

@router.get("/session-plans/{patient_id}")
async def get_session_plan(patient_id: str, session_number: int = None, current_user: dict = Depends(get_current_user)):
    supabase = get_supabase()
    query = supabase.table("session_plans").select("*").eq("patient_id", patient_id)
    if session_number:
        query = query.eq("session_number", session_number)
    resp = query.order("created_at", desc=True).limit(1).execute()
    return resp.data[0] if resp.data else None

# FINALIZED TREATMENT PLANS (New Dedicated Table)
@router.post("/treatment-plans")
async def finalize_treatment_plan(data: dict, current_user: dict = Depends(get_current_user)):
    supabase = get_supabase()
    
    insert_data = {
        "patient_id": data.get("patient_id"),
        "session_number": int(data.get("session_number", 1)),
        "appointment_id": data.get("appointment_id"),
        "finalized_content": data.get("finalized_content"),
        "chat_history": data.get("chat_history"), # Added persistence for consultations
        "clinical_snapshot": data.get("clinical_snapshot"),
        "created_by": current_user["id"],
        "status": data.get("status", "active")
    }
    
    # Final treatment plans are unique per patient/session/appointment.
    # We use upsert to handle revisions gracefully.
    resp = supabase.table("treatment_plans").upsert(insert_data, on_conflict="patient_id,session_number").execute()

    if not resp.data:
        raise HTTPException(status_code=400, detail="Failed to finalize treatment plan")
    return resp.data[0]

@router.get("/treatment-plans/{patient_id}")
async def get_finalized_treatment_plan(patient_id: str, appointment_id: str = None, session_number: int = None, current_user: dict = Depends(get_current_user)):
    supabase = get_supabase()
    query = supabase.table("treatment_plans").select("*").eq("patient_id", patient_id)
    
    if appointment_id:
        query = query.eq("appointment_id", appointment_id)
    if session_number:
        query = query.eq("session_number", session_number)
        
    resp = query.order("created_at", desc=True).limit(1).execute()
    return resp.data[0] if resp.data else None
